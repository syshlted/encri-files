#!/usr/bin/env python3
"""Write docs/decisions/INDEX.md from the decision files and the component briefs.

A copy of encri's script (encri D127), reading F numbers instead of D numbers.

Run from the repository root after adding, retitling or re-citing a decision:

    python3 scripts/docs/decision-index.py .

Every column is read from the files themselves, so the index is never edited by hand. It also
appends to each record a generated footer copying the entries of `amendments.md` that amend it, so
a reader who opens one record sees its later corrections. Only the footer is ever rewritten.
"""
import re
import sys
from pathlib import Path

HEADING = re.compile(r"^# (F\d+a?) — (.*)$")
HEADING_NOTE = re.compile(r"\s\*(Amended|Both)\b.*$")
DATED = re.compile(r"\*(\d{4}-\d\d-\d\d)\s*[·,]\s*(.*)$")
UNDATED = {}
D_REF = re.compile(r"\bF(\d+a?)\b")


def key(did):
    m = re.match(r"F(\d+)(a?)", did)
    return int(m.group(1)), m.group(2)


def status_of(lines):
    joined = []
    for i, line in enumerate(lines[1:16], start=1):
        m = DATED.search(line)
        if m:
            text = m.group(2)
            # an italic status line may wrap onto the next lines
            j = i + 1
            while "*" not in text.rstrip("*").rstrip() and j < len(lines) and lines[j].strip():
                text += " " + lines[j].strip()
                j += 1
            clause = re.split(r";|\. |—", text.replace("**", ""))[0]
            clause = clause.replace(" (below)", "").strip(" *.")
            return m.group(1), clause[:110]
        joined.append(line)
    text = "".join(lines[1:6])
    date = re.search(r"\d{4}-\d\d-\d\d", text)
    st = re.search(r"\*\*Status:\*\*\s*([^.\n]*)", text)
    return (date.group(0) if date else "—"), (st.group(1).strip() if st else "")


FOOTER_START = "<!-- amendments: generated by scripts/docs/decision-index.py; do not edit -->"
FOOTER_END = "<!-- /amendments -->"
LEAD = re.compile(r"^- \*\*(.*?)\*\*", re.S)
POSSESSIVE = re.compile(r"\bF(\d+a?)(?: and F(\d+a?))?'s\b")


def amendment_entries(ddir):
    """Map a decision id to the amendments.md entries whose bold lead names it possessively."""
    lines = (ddir / "amendments.md").read_text().splitlines(keepends=True)
    entries, current = [], None
    for line in lines:
        if line.startswith("- "):
            current = [line]
            entries.append(current)
        elif current is not None and (line.startswith("  ") or not line.strip()):
            current.append(line)
        else:
            current = None
    found = {}
    for entry in entries:
        text = "".join(entry).rstrip() + "\n"
        lead = LEAD.match(text)
        if not lead:
            continue
        for m in POSSESSIVE.finditer(lead.group(1)):
            for did in filter(None, m.groups()):
                found.setdefault("F" + did, []).append(text)
    return found


def with_footer(text, entries):
    if FOOTER_START in text:
        text = text[: text.index(FOOTER_START)].rstrip("\n") + "\n"
    if not entries:
        return text
    body = "".join(entries)
    return (
        text.rstrip("\n") + "\n\n" + FOOTER_START + "\n\n"
        "## Amended since, as recorded in `amendments.md`\n\n" + body + "\n" + FOOTER_END + "\n"
    )


def briefs_citing(repo):
    cited = {}
    rules = repo / ".claude" / "rules"
    for f in sorted(rules.glob("*.md")) if rules.exists() else []:
        for ref in set(D_REF.findall(f.read_text())):
            cited.setdefault("F" + ref, []).append(f.stem)
    return cited


def main():
    repo = Path(sys.argv[1])
    ddir = repo / "docs" / "decisions"
    cited = briefs_citing(repo)
    amended = amendment_entries(ddir)
    rows = []
    for f in ddir.glob("F*.md"):
        did_line = f.read_text().splitlines()[0]
        did_here = HEADING.match(did_line).group(1)
        updated = with_footer(f.read_text(), amended.get(did_here, []))
        if updated != f.read_text():
            f.write_text(updated)
        lines = f.read_text().splitlines()
        m = HEADING.match(lines[0])
        did, title = m.group(1), HEADING_NOTE.sub("", m.group(2)).strip()
        date, status = status_of(lines)
        date = UNDATED.get(did, date)
        n = len(amended.get(did, []))
        rows.append((key(did), did, f.name, date, title, status, str(n) if n else "",
                     ", ".join(cited.get(did, []))))
    rows.sort()
    out = [
        "# encri-files — decision index\n",
        "\n",
        "Level 2 of the knowledge map in `AGENTS.md`: one line per decision. The full record is the\n",
        "linked file (level 3). *Briefs* names the component briefs in `.claude/rules/` (level 1) that\n",
        "cite the decision. *Status* is the first clause of the record's own status line. *Amended* counts\n",
        "the entries of `amendments.md` that correct the record; each record carries them in a footer.\n",
        "Read the record before relying on it: later decisions also amend earlier ones in place.\n",
        "\n",
        "Generated by `scripts/docs/decision-index.py`; do not edit it by hand.\n",
        "\n",
        "| Decision | Date | Title | Status | Amended | Briefs |\n",
        "|---|---|---|---|---|---|\n",
    ]
    for _, did, name, date, title, status, amends, briefs in rows:
        title = title.replace("|", "\\|")
        status = status.replace("|", "\\|")
        out.append(f"| [{did}]({name}) | {date} | {title} | {status} | {amends} | {briefs} |\n")
    (ddir / "INDEX.md").write_text("".join(out))
    print(len(rows), "rows")


if __name__ == "__main__":
    main()
